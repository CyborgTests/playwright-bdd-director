import type { Background, Rule, Scenario, Step, Tag } from '@cucumber/messages'
import path from 'path'
import prettier from 'prettier'

import { getBackgroundTitle, parseGherkinDocument } from '../core/gherkin-parser'
import { quoteString } from '../generation/examples-code'
import { extractSuiteName, getTagConstant } from '../generation/tags-updater'
import { fillPlaceholders, getMarkdownBaseName } from '../utils/helpers'
import type { BddGeneration } from './generator'

/** Special tags a person can follow; @fail, @slow, @retries, @timeout are about automation */
const MODIFIER_TAGS = ['@skip', '@fixme'] as const

/**
 * Cyborg test of a Gherkin spec, generated as a whole like its automated test - a person walks
 * every step (manualStep with the spec text):
 * Feature → describe "[CYBORG] …", Background → beforeEach (Rule Background too), Rule → nested
 * describe, Scenario → test, Outline → test per Examples row; @skip / @fixme → test modifiers.
 */
export async function generateBddCyborgTest(
  specPath: string,
  testPath: string
): Promise<BddGeneration> {
  const feature = parseGherkinDocument(specPath).feature
  if (!feature) throw new Error(`No "Feature:" in ${specPath}`)

  const featureTags = tagNames(feature.tags)
  const suiteTag = getTagConstant(extractSuiteName(getMarkdownBaseName(specPath)))
  const suiteTags = ['TAG.TEST.CYBORG', `TAG.SUITE.${suiteTag}`, ...featureTags.map(quoteString)]
  const body = feature.children.flatMap((child) => {
    if (child.background) return emitBackground(child.background)
    if (child.scenario) return emitScenario(child.scenario, featureTags)
    if (child.rule) return emitRule(child.rule, featureTags)
    return []
  })

  const source = [
    `// Generated by npm run stage from ${toPosix(specPath)} - change the spec, not this file`,
    "import test from '@cyborgtests/test'",
    '',
    "import { TAG } from '@/test-constants/tags'",
    '',
    `test.describe(${quoteString(`[CYBORG] ${feature.name.trim()}`)}, { tag: [${suiteTags.join(', ')}] }, () => {`,
    ...body,
    '})'
  ].join('\n')

  const options = await prettier.resolveConfig(testPath)
  const content = await prettier.format(source, { ...options, filepath: testPath })
  return { specPath, testPath, content, missing: [], ambiguous: [] }
}

function emitBackground(background: Background, ruleName?: string): string[] {
  return [
    `test.beforeEach(${quoteString(getBackgroundTitle(background, ruleName))}, async (${manualParam(background.steps)}) => {`,
    ...emitSteps(background.steps, {}),
    '})',
    ''
  ]
}

function emitRule(rule: Rule, inherited: string[]): string[] {
  const own = tagNames(rule.tags)
  const details = own.length > 0 ? `${tagDetails(own)}, ` : ''
  return [
    `test.describe(${quoteString(rule.name.trim())}, ${details}() => {`,
    ...rule.children.flatMap((child) => {
      if (child.background) return emitBackground(child.background, rule.name.trim())
      if (child.scenario) return emitScenario(child.scenario, [...inherited, ...own])
      return []
    }),
    '})',
    ''
  ]
}

/** One test, or one per Examples row with the row values filled in */
function emitScenario(scenario: Scenario, inherited: string[]): string[] {
  const blocks = scenario.examples.filter((block) => block.tableHeader)
  if (blocks.length === 0) return emitTest(scenario, {}, tagNames(scenario.tags), inherited)

  return blocks.flatMap((block) => {
    const columns = block.tableHeader!.cells.map((cell) => cell.value)
    const own = [...tagNames(scenario.tags), ...tagNames(block.tags)]
    return block.tableBody.flatMap((row) =>
      emitTest(
        scenario,
        Object.fromEntries(columns.map((column, i) => [column, row.cells[i].value])),
        own,
        inherited
      )
    )
  })
}

function emitTest(
  scenario: Scenario,
  values: Record<string, string>,
  own: string[],
  inherited: string[]
): string[] {
  const tags = [...inherited, ...own]
  const modifier = MODIFIER_TAGS.find((tag) => tags.includes(tag))?.slice(1)
  const declare = modifier ? `test.${modifier}` : 'test'
  const details = own.length > 0 ? `${tagDetails([...new Set(own)])}, ` : ''
  const name = fillPlaceholders(scenario.name.trim(), values)
  return [
    `${declare}(${quoteString(name)}, ${details}async (${manualParam(scenario.steps)}) => {`,
    ...emitSteps(scenario.steps, values),
    '})',
    ''
  ]
}

function emitSteps(steps: readonly Step[], values: Record<string, string>): string[] {
  return steps.map(
    (step) =>
      `await manualStep(${quoteString(fillPlaceholders(`${step.keyword.trim()} ${step.text.trim()}`, values))})`
  )
}

function manualParam(steps: readonly Step[]): string {
  return steps.length > 0 ? '{ manualStep }' : ''
}

function tagDetails(tags: string[]): string {
  return `{ tag: [${tags.map(quoteString).join(', ')}] }`
}

function tagNames(tags: readonly Tag[]): string[] {
  return tags.map((tag) => tag.name)
}

function toPosix(filePath: string): string {
  return filePath.split(path.sep).join('/')
}
